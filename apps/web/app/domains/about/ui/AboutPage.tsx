function Datasets() {
  return (
    <Stack direction="column" gap="6">
      <Stack direction="column" gap="1">
        <Heading size="lg">Available datasets</Heading>
        <Text color="fg.muted">
          Each dataset is published as a single Parquet file and loaded once
          per browser. Schema and row types are derived from a single
          definition in <Badge variant="subtle">@bankql/schema</Badge>.
        </Text>
      </Stack>

      <Stack direction="column" gap="3">
        {publishedDatasets.map((dataset) => (
          <Card.Root key={dataset.name} variant="outline">
            <Card.Body>
              <Stack direction="row" align="center" gap="3" mb="2">
                <Box color="fg.muted">
                  <LuTable />
                </Box>
                <Card.Title fontFamily="mono" fontSize="md">
                  {dataset.name}
                </Card.Title>
                <Badge variant="subtle">
                  {Object.keys(dataset.fields).length} columns
                </Badge>
              </Stack>
              {dataset.description && (
                <Card.Description>{dataset.description}</Card.Description>
              )}
            </Card.Body>
          </Card.Root>
        ))}
      </Stack>
    </Stack>
  );
}
