function Intro() {
  return (
    <Stack direction="column" gap="4">
      <Heading size="2xl">How bankql works</Heading>
      <Text color="fg.muted" textStyle="lg">
        bankql is a browser-native exploration tool for U.S. banking data.
        FDIC, NCUA, and Federal Reserve datasets are pre-processed into
        Parquet files, then loaded directly into a SQL engine running inside
        your tab.
      </Text>
      <Text color="fg.muted">
        That means every query — typed by hand or generated by the assistant —
        runs locally against your own copy of the data. Nothing about your
        questions or your results is sent to a server.
      </Text>
    </Stack>
  );
}

